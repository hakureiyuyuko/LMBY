// variantFold 是解析后的对照表（异体 → 常用形）。
var variantFold = buildVariantFold()

// variantProblems 收集表里的格式问题，由单测断言为空。
var variantProblems []string

func buildVariantFold() map[rune]rune {
	m := make(map[rune]rune, 1024)
	for _, group := range variantGroups {
		for _, field := range strings.Fields(group) {
			rs := []rune(field)
			if len(rs) != 2 {
				variantProblems = append(variantProblems, "字段必须正好 2 个字: "+field)
				continue
			}
			if rs[0] == rs[1] {
				variantProblems = append(variantProblems, "两边相同，无意义: "+field)
				continue
			}
			if prev, dup := m[rs[0]]; dup {
				variantProblems = append(variantProblems, "重复的异体字 "+string(rs[0])+
					"（已映射到 "+string(prev)+"，又要映射到 "+string(rs[1])+"）")
				continue
			}
			m[rs[0]] = rs[1]
		}
	}
	return m
}
